/* ---------------------------------------------------------------------------
 * L'assemblage : chaque langue = { nom natif, textes }. Le français est la
 * source ; les 8 autres doivent porter EXACTEMENT ses clés (test d'inventaire).
 * ------------------------------------------------------------------------- */
const fusion = (base, extra) => ({ ...base, ...extra });

export const LANGUES = {
  fr: { nom: 'Français', textes: fusion(FR, EXTRA.fr) },
  nl: { nom: 'Nederlands', textes: fusion(NL, EXTRA.nl) },
  de: { nom: 'Deutsch', textes: fusion(DE, EXTRA.de) },
  en: { nom: 'English', textes: fusion(EN, EXTRA.en) },
  es: { nom: 'Español', textes: fusion(ES, EXTRA.es) },
  it: { nom: 'Italiano', textes: fusion(IT, EXTRA.it) },
  pt: { nom: 'Português', textes: fusion(PT, EXTRA.pt) },
  pl: { nom: 'Polski', textes: fusion(PL, EXTRA.pl) },
  sv: { nom: 'Svenska', textes: fusion(SV, EXTRA.sv) },
};

/* ---------------------------------------------------------------------------
 * État courant + accès au stockage.
 * Toutes les références au navigateur sont GARDÉES (typeof) : le module doit
 * pouvoir être chargé hors navigateur (tests Node) sans exploser.
 * ------------------------------------------------------------------------- */
let langueCourante = LANGUE_DEFAUT;

function memoLangue() {
  try { return typeof localStorage !== 'undefined' ? localStorage.getItem(CLE_LANGUE) : null; }
  catch { return null; }
}
function ecrireMemoLangue(code) {
  try { if (typeof localStorage !== 'undefined') localStorage.setItem(CLE_LANGUE, code); }
  catch { /* navigation privée : on s'en passe */ }
}

/** Cette langue est-elle offerte ? */
export const estLangue = (code) => Object.prototype.hasOwnProperty.call(LANGUES, code);

/** La langue actuellement affichée. */
export const langue = () => langueCourante;

/** Nom natif d'une langue (« Deutsch », « Nederlands »…). */
export const nomLangue = (code) => (LANGUES[code] && LANGUES[code].nom) || code;

/** Liste ordonnée des langues du sélecteur : { code, nom }. */
export const languesDisponibles = () => LANGUES_OFFERTES.map((l) => ({ ...l }));

/** Étiquette de locale pour les dates / nombres de la langue courante. */
export const locale = (code = langueCourante) => LOCALES[code] || LOCALES[LANGUE_DEFAUT];

/** Langue du navigateur si elle est offerte, sinon la langue par défaut. */
export function langueDetectee() {
  let brut = '';
  try { brut = (typeof navigator !== 'undefined' && navigator.language) || ''; } catch { /* rien */ }
  const base = String(brut).toLowerCase().split('-')[0];
  return estLangue(base) ? base : LANGUE_DEFAUT;
}

/** Langue mémorisée si valide, sinon celle du navigateur, sinon le défaut. */
export function chargerLangue() {
  const memo = memoLangue();
  const code = estLangue(memo) ? memo : langueDetectee();
  /* ⚠ Elle APPLIQUE la langue, elle ne fait pas que la rendre.
   *
   *  Défaut mesuré le 7/10, en rechargeant la page après un test : l'application
   *  appelait chargerLangue() puis traduisait le DOM, mais la langue courante
   *  n'était jamais changée. La page repartait donc en français à chaque
   *  chargement, et ne redevenait allemande qu'après un passage MANUEL dans les
   *  Réglages — le choix de l'utilisateur ne survivait pas à un rechargement.
   *
   *  On n'écrit PAS la mémoire ici : tant que l'utilisateur n'a rien choisi, la
   *  langue détectée reste une proposition, pas une décision enregistrée. */
  if (estLangue(code)) langueCourante = code;
  return code;
}

/** Interpole les {cle} d'un gabarit avec les variables fournies. */
export function interpole(texte, variables) {
  if (variables == null) return texte;
  return String(texte).replace(/\{(\w+)\}/g, (m, k) => (variables[k] != null ? String(variables[k]) : m));
}

/* Clé NORMALISÉE : pour l'utilisateur, « Lire l’article » (apostrophe courbe) et
 * « Lire l'article » (apostrophe droite) sont le MÊME mot. Défaut mesuré le
 * 7/10 : le code écrit la courbe, les dictionnaires gardent la droite — la clé
 * n'était donc pas trouvée, et le bouton restait en français SANS aucune erreur
 * visible. On indexe chaque langue sur ses clés normalisées, et on cherche
 * d'abord la clé exacte (rapide), puis la normalisée. */
export const normaliseCle = (s) => String(s).replace(/[\u2018\u2019]/g, "'").replace(/\s+/g, ' ').trim();
const INDEX_NORM = {};
function indexNormalise(code) {
  if (INDEX_NORM[code]) return INDEX_NORM[code];
  const dico = (LANGUES[code] && LANGUES[code].textes) || {};
  const m = {};
  for (const [k, v] of Object.entries(dico)) m[normaliseCle(k)] = v;
  INDEX_NORM[code] = m;
  return m;
}

/**
 * Traduit une clé (le texte français) dans la langue courante.
 * Si la clé n'existe pas, elle est rendue TELLE QUELLE (français) : aucune
 * chaîne ne disparaît jamais de l'écran.
 */
export function t(cle, variables) {
  const dico = LANGUES[langueCourante] && LANGUES[langueCourante].textes;
  let brut = dico && Object.prototype.hasOwnProperty.call(dico, cle) ? dico[cle] : null;
  if (brut == null) brut = indexNormalise(langueCourante)[normaliseCle(cle)];
  if (brut == null) brut = cle;
  return interpole(brut, variables);
}

/**
 * Fixe la langue courante, la mémorise, et pose `document.documentElement.lang`.
 * Ne touche JAMAIS au pays : les deux choix vivent dans deux clés distinctes.
 * @returns {boolean} vrai si la langue a été acceptée
 */
export function definirLangue(code) {
  if (!estLangue(code)) return false;
  langueCourante = code;
  ecrireMemoLangue(code);
  try {
    if (typeof document !== 'undefined' && document.documentElement) document.documentElement.lang = code;
  } catch { /* rien */ }
  return true;
}

/* Attributs porteurs de texte, avec la cible à écrire. */
const ATTRS = [
  ['data-i18n', null],                    // texte de l'élément
  ['data-i18n-placeholder', 'placeholder'],
  ['data-i18n-title', 'title'],
  ['data-i18n-aria-label', 'aria-label'],
];

/**
 * Applique la langue courante au DOM : pour chaque élément portant un attribut
 * `data-i18n*` de index.html, pose le texte ou l'attribut traduit. C'est ce qui
 * traduit la partie STATIQUE de la page (en-tête, feuille Réglages, modales).
 * @returns {number} nombre de points traduits (utile à la mesure)
 */
export function traduireDOM(racine) {
  const doc = racine || (typeof document !== 'undefined' ? document : null);
  if (!doc || typeof doc.querySelectorAll !== 'function') return 0;
  let n = 0;
  for (const [attr, cible] of ATTRS) {
    for (const el of doc.querySelectorAll(`[${attr}]`)) {
      const cle = el.getAttribute(attr);
      const texte = t(cle);
      if (cible) el.setAttribute(cible, texte);
      else el.textContent = texte;
      n += 1;
    }
  }
  return n;
}
